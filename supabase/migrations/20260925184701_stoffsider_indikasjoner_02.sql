    objekt := (public.opprett_utkast('innholdselement', jsonb_build_object(
      'infoside', side_0,
    'panel', 'indikasjon',
    'posisjon', 0,
    'elementtype', 'riktekst',
    'data', '{"dokument":{"type":"doc","content":[{"type":"paragraph","content":[{"type":"text","text":"Lithionit: profylaktisk ved maniske og depressive faser i manisk-depressiv sykdom, og terapeutisk ved maniske tilstander."}]},{"type":"paragraph","content":[{"type":"text","text":"Carblit (voksne ≥18 år): mani; antimanisk behandling av bipolar lidelse og profylakse for å forebygge alvorlige, hyppige faser; f'
    'orsterkning til et antidepressiv ved alvorlig depressiv lidelse."}]}]}}'::jsonb,
    'referanser', jsonb_build_array(referanse_0, referanse_1)
    ))).id;
    nye := nye || objekt;
  end if;

  -- Alt som ble opprettet, publiseres i den rekkefølgen det ble laget:
  -- referansene og sidene før det som peker på dem.
  foreach objekt in array nye loop
    perform public.publiser_utkast(objekt, 1);
  end loop;
end
